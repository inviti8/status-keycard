package im.status.keycard;

import javacard.security.*;

/**
 * Keep references to data structures shared across applet instances of this package.
 */
class SharedMemory {
  static final short CERT_LEN = 98;

  /** The NDEF data file. Read through the NDEFApplet. **/
  static final byte[] ndefDataFile = new byte[NDEFApplet.NDEF_MAX_SIZE];

  /** The Cash data file. Read through the CashApplet. **/
  static final byte[] cashDataFile = new byte[KeycardApplet.MAX_DATA_LENGTH + 1];

  /** The identification private key. Generated on card, never exported. **/
  static ECPrivateKey idPrivate = null;

  /** The identification key pair, generated by GENERATE IDENTITY. **/
  static KeyPair idKeyPair = null;

  /** The identity state (byte 0: IdentApplet.ID_EMPTY, ID_GENERATED or CERT_VALID) followed by the certificate. The
   * certificate is the concatenation of: compressed id public key, CA signature. The signature is in the format r,s,v
   * where v allows recovering the signer public key. In the generated state only the public key is set. */
  static final byte[] idCert = new byte[(short)(CERT_LEN + 1)];
}
